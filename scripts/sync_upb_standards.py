#!/usr/bin/env python3
"""Copy a revision of upb-standards from Git into the packaged data snapshot."""
from __future__ import annotations

import argparse
import hashlib
import io
import json
from pathlib import Path, PurePosixPath
import shutil
import subprocess
import tarfile
import tomllib

REPOSITORY = "https://github.com/duserzym/upb-standards"
DEFAULT_REV = "47c15a5998db3ccf74a8886c6412ece16e66df20"
SNAPSHOT = Path(__file__).resolve().parents[1] / "UPbRPy/reference_materials"
MINERALS = {"apatite", "carbonate", "glass", "hematite", "rutile", "titanite", "zircon"}


def _git(checkout: Path, *args: str) -> bytes:
    return subprocess.check_output(
        ["git", "--no-optional-locks", "-C", str(checkout), *args],
        stdin=subprocess.DEVNULL,
    )


def sync(checkout: Path, rev: str = DEFAULT_REV, *, destination: Path = SNAPSHOT) -> None:
    """Replace destination with committed TOML data, license and revision metadata.

    Only Git objects are read; uncommitted files in checkout are ignored.
    """
    commit, commit_date = _git(checkout, "show", "-s", "--format=%H%n%cI", rev).decode().strip().splitlines()
    copied = {}
    with tarfile.open(fileobj=io.BytesIO(_git(checkout, "archive", commit)), mode="r:") as archive:
        for member in archive:
            path = PurePosixPath(member.name)
            selected = member.name in {"library.toml", "sources.toml", "LICENSE"} or (
                len(path.parts) >= 2 and path.parts[0] in MINERALS and path.suffix == ".toml"
            )
            if selected:
                if not member.isfile() or path.is_absolute() or ".." in path.parts:
                    raise ValueError(f"Not a regular data file: {member.name}")
                copied[member.name] = archive.extractfile(member).read()
    for required in ("library.toml", "sources.toml", "LICENSE"):
        if required not in copied:
            raise ValueError(f"Missing upstream {required}")
    if not copied["LICENSE"].startswith(b"MIT License\n"):
        raise ValueError("Upstream license changed; review it before copying data")
    manifest = tomllib.loads(copied["library.toml"].decode())
    if manifest["sources"] != "sources.toml" or not set(manifest["material_files"]) <= copied.keys():
        raise ValueError("Upstream manifest refers to files outside the data snapshot")
    quote = json.dumps
    metadata = [
        "# Generated by scripts/sync_upb_standards.py; do not edit.",
        f"repository = {quote(REPOSITORY)}", f"commit = {quote(commit)}",
        f"commit_date = {quote(commit_date)}", 'license = "MIT"', "files = [",
        *(f"  {quote(name)}," for name in sorted(copied)), "]", "", "[sha256]",
        *(f"{quote(name)} = {quote(hashlib.sha256(data).hexdigest())}" for name, data in sorted(copied.items())),
        "",
    ]
    # Finish reading and validating the revision before replacing the old data.
    if destination.exists():
        shutil.rmtree(destination)
    destination.mkdir(parents=True)
    for name, data in copied.items():
        target = destination / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    (destination / "UPSTREAM.toml").write_text("\n".join(metadata), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("checkout", type=Path)
    parser.add_argument("--rev", default=DEFAULT_REV, help="Git revision (default: pinned snapshot commit)")
    args = parser.parse_args()
    sync(args.checkout.expanduser(), args.rev)


if __name__ == "__main__":
    main()
