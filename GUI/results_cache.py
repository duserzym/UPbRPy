"""Local, disposable saved-project results. This module never imports Qt.

Pickles are trusted only in the user's private cache, never beside a project.
Keys conservatively fingerprint all package code, including modules not used by
this particular workflow. Dependencies use content, never modification times.
"""
from __future__ import annotations

from dataclasses import dataclass, replace
import hashlib
import importlib
import json
import logging
import marshal
import os
import operator
from pathlib import Path
import platform
import sys
import stat
import tempfile
import time
import zlib

CACHE_FORMAT = 1
# Each is consumed only by display/install code. In particular export_settings,
# bias_controls, review records and all unknown keys remain scientific inputs.
VIEW_ONLY = frozenset({
    "selected_spot", "plot_mode", "visible_channels", "selected_stats_channel",
    "ratio_name", "workflow_stage", "sigma_level", "channel_colors",
    "selection_colors", "review_spot_colour", "review_depth_colormap",
    "review_show_glasses",
})
_logger = logging.getLogger(__name__)


def cache_directory() -> Path:
    """Return the platform cache directory, respecting the explicit override."""
    if value := os.environ.get("UPBRPY_RESULTS_CACHE_DIR"):
        return Path(value).expanduser().resolve()
    if sys.platform == "darwin":
        root = Path.home() / "Library/Caches"
    elif sys.platform == "win32":
        root = Path(os.environ["LOCALAPPDATA"])
    else:
        root = Path(os.environ.get("XDG_CACHE_HOME", Path.home() / ".cache"))
    return root / "UPbRPy/results"


def enabled() -> bool:
    return os.environ.get("UPBRPY_RESULTS_CACHE") != "0"


def _json(value) -> bytes:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), allow_nan=False).encode()


def _file(path) -> dict:
    if not stat.S_ISREG(Path(path).stat().st_mode):
        raise ValueError(f"Not a regular input file: {path}")
    digest = hashlib.sha256()
    size = 0
    with Path(path).open("rb") as stream:
        while chunk := stream.read(1024 * 1024):
            digest.update(chunk)
            size += len(chunk)
    return {"sha256": digest.hexdigest(), "size": size}


def engine_fingerprint() -> str:
    """Hash a conservative superset of restore modules, also in frozen apps."""
    from UPbRPy.pipeline import package_version
    import numpy
    import pandas
    import scipy

    # platform.platform() can run uname through a pipe on first use. Resolve
    # this library/runtime metadata before auditing scientific input reads;
    # the same value is later generated by pipeline.manifest().
    runtime_platform = platform.platform()
    digest = hashlib.sha256(_json([CACHE_FORMAT, package_version(), sys.version,
                                 numpy.__version__, pandas.__version__, scipy.__version__,
                                 runtime_platform]))
    for package_name in ("UPbRPy", "GUI"):
        package = importlib.import_module(package_name)
        root = Path(package.__file__).parent
        loader = package.__spec__.loader
        # PyInstaller's importer exposes the full PYZ table. Avoid importing
        # modules to enumerate it: GUI modules would import Qt in the child.
        toc = getattr(loader, "toc", None)
        if toc is None:
            toc = getattr(getattr(loader, "_pyz_archive", None), "toc", None)
        names = {package_name}
        if toc is not None:
            names.update(name for name in toc if name.startswith(package_name + "."))
        for path in root.rglob("*.py"):
            relative = path.relative_to(root).with_suffix("")
            parts = relative.parts
            name = ".".join((package_name, *parts))
            if parts[-1] == "__init__":
                name = ".".join((package_name, *parts[:-1]))
            names.add(name)
        names.update(name for name in sys.modules if name == package_name or name.startswith(package_name + "."))
        for name in sorted(names):
            relative = name.split(".")[1:]
            source = root.joinpath(*relative).with_suffix(".py") if relative else root / "__init__.py"
            if not source.is_file():
                source = root.joinpath(*relative, "__init__.py")
            archive = getattr(loader, "_pyz_archive", None)
            if source.is_file():
                code = source.read_bytes()
            elif archive is not None and hasattr(archive, "extract") and name in (toc or ()):
                # Frozen app: hash the module's bytes as stored in the PYZ.
                # Re-marshalling a loaded code object is not stable: marshal
                # marks objects by reference count, which grows as the
                # restore imports more modules, so the key changed between
                # lookup and store and no entry was ever written.
                code = archive.extract(name, raw=True)
            else:
                # PathFinder consults PyInstaller's path hook without executing
                # a parent package (which could import Qt).
                spec = package.__spec__ if not relative else importlib.machinery.PathFinder.find_spec(
                    name, [str(root.joinpath(*relative[:-1]))])
                code_object = spec.loader.get_code(name)
                if code_object is None:
                    raise ValueError(f"Cannot fingerprint {name}")
                code = marshal.dumps(code_object)
            digest.update(name.encode() + b"\0" + code)
    return digest.hexdigest()


@dataclass
class CacheRequest:
    project: Path
    document: dict
    source: Path
    reference: Path
    engine: str
    key: str


def prepare(project_file) -> CacheRequest | None:
    """Read the current document and build a lookup key; failures disable caching."""
    if not enabled():
        return None
    try:
        from GUI.services import DEFAULT_REFERENCE_LIBRARY_PATH
        from UPbRPy.project import read_reduction_project, resolve_project_path
        project = Path(project_file).expanduser().resolve()
        document = read_reduction_project(project)
        source = resolve_project_path(project, document["paths"].get("source_directory"), label="raw data")
        reference = resolve_project_path(project, document["paths"].get("reference_library"),
                                         label="reference library", required=False)
        reference = reference or Path(DEFAULT_REFERENCE_LIBRARY_PATH).resolve()
        scientific = dict(document)
        scientific["workspace"] = {k: v for k, v in document.get("workspace", {}).items() if k not in VIEW_ONLY}
        engine = engine_fingerprint()
        manifest = document["pipeline"]["config"].get("selection_options", {}).get("session_manifest")
        manifest_path = str(Path(manifest).expanduser().resolve()) if isinstance(manifest, str) else None
        key = hashlib.sha256(_json([scientific, str(source), str(reference), manifest_path, engine])).hexdigest()
        return CacheRequest(project, document, source, reference, engine, key)
    except Exception:
        _logger.debug("Results cache key unavailable", exc_info=True)
        return None


def _listing(path) -> list[str]:
    # Qtegra discovery only considers CSVs and directories; .upbr files and
    # their atomic-write temporaries cannot affect it. Ignore only these known
    # project artifacts, so Save/autosave in the raw folder cannot poison hits.
    cache = cache_directory()
    ignored = cache.name if Path(path).resolve() == cache.parent else None
    names = []
    with os.scandir(path) as entries:
        for entry in entries:
            if entry.name == ignored:
                continue
            directory = entry.is_dir()
            artifact = entry.name.lower().endswith(".upbr") or (
                entry.name.startswith(".") and ".upbr." in entry.name.lower()
                and entry.name.endswith(".tmp"))
            if artifact and not directory:
                continue
            # A companion directory may have any name, including *.upbr.
            # Mark directory types to catch an unchanged name becoming a
            # companion folder where a non-input file previously stood.
            names.append(entry.name + ("/" if directory else ""))
    return sorted(names)


class _AuditSink:
    """Route file events to Python; ignore frequent reflection events in C."""

    __slots__ = ("callback", "__dict__")

    def __init__(self, callback):
        self.callback = callback

    def opened(self, args):
        self.callback("open", args)

    def listed(self, args):
        self.callback("os.listdir", args)

    def scanned(self, args):
        self.callback("os.scandir", args)

    open = property(fset=opened)


setattr(_AuditSink, "os.listdir", property(fset=_AuditSink.listed))
setattr(_AuditSink, "os.scandir", property(fset=_AuditSink.scanned))
for _event in ("object.__getattr__", "object.__setattr__", "object.__delattr__", "sys._getframe"):
    setattr(_AuditSink, _event, property(fset=operator.is_))


class DependencyRecorder:
    """Audit reads only during a child restore, hashing before and after use."""

    def __init__(self, request: CacheRequest):
        self.request = request
        self.files = {}
        self.directories = {}
        self.aliases = {}
        self.active = False
        self.busy = False
        self.valid = True
        self.excluded = [Path(sys.prefix).resolve(), Path(sys.base_prefix).resolve(), cache_directory()]
        self.excluded.extend(Path(importlib.import_module(name).__file__).resolve().parent for name in ("GUI", "UPbRPy"))
        if hasattr(sys, "_MEIPASS"):
            self.excluded.append(Path(sys._MEIPASS).resolve())

    def _resolve(self, path):
        original = Path(os.path.abspath(path))
        resolved = original.resolve()
        if original != resolved:
            target = str(resolved)
            if str(original) in self.aliases and self.aliases[str(original)] != target:
                self.valid = False
            self.aliases[str(original)] = target
        return resolved

    def _record_file(self, path, *, optional=False):
        path = self._resolve(path)
        key = str(path)
        try:
            value = _file(path)
        except FileNotFoundError:
            if not optional:
                raise
            value = {"missing": True}
        if key in self.files and self.files[key] != value:
            self.valid = False
        self.files[key] = value

    def _tree(self, path):
        path = self._resolve(path)
        if path.is_dir():
            self.directories[str(path)] = _listing(path)
            for child in path.iterdir():
                self._tree(child)
        else:
            self._record_file(path)

    def __enter__(self):
        # Include package resources read during import, before the audit scope.
        from GUI.services import DEFAULT_REFERENCE_LIBRARY_PATH
        import UPbRPy
        reference = self.request.reference
        self._tree(reference.parent if reference.name == "library.toml" else reference)
        self._tree(DEFAULT_REFERENCE_LIBRARY_PATH)
        self._record_file(Path(UPbRPy.__file__).parent / "standards.csv")
        folder = self.request.source if self.request.source.is_dir() else self.request.source.parent
        # stat/is_file probes do not emit open events. Track absence as well as
        # presence, so adding a manifest (or bundle raw folder) invalidates.
        for parent in (folder, folder.parent) if folder.name == "raw" else (folder,):
            self._record_file(parent / "session_manifest.toml", optional=True)
        self.directories[str(folder)] = _listing(folder)
        self.sink = _AuditSink(self._audit)
        sys.addaudithook(self.sink.__setattr__)
        self.active = True
        return self

    def _audit(self, event, args):
        if not self.active or self.busy or event not in {"open", "os.listdir", "os.scandir"}:
            return
        self.busy = True
        try:
            value = args[0]
            if not isinstance(value, (str, bytes, os.PathLike)):
                # An existing descriptor has no path we can validate. Only
                # write-only descriptors can safely be ignored.
                writing = event == "open" and (
                    (isinstance(args[1], str) and args[1].startswith(("w", "a", "x")))
                    or args[2] & os.O_WRONLY)
                if not writing:
                    self.valid = False
                return
            path = Path(os.fsdecode(value)).resolve()
            # subprocess libraries open the null device read/write. It supplies
            # no input bytes; other non-regular reads disable caching.
            if path == Path(os.devnull).resolve():
                return
            if path == self.request.project or any(path.is_relative_to(root) for root in self.excluded):
                return
            # Distribution metadata (version lookups) is already part of the
            # engine fingerprint, and an editable install rewrites it in place.
            if any(part.endswith((".egg-info", ".dist-info")) for part in path.parts):
                return
            self._resolve(os.fsdecode(value))
            if event == "open":
                mode, flags = args[1:3]
                if (isinstance(mode, str) and mode.startswith(("w", "a", "x"))) or flags & os.O_WRONLY:
                    return  # Library cache writes are not input dependencies.
                self._record_file(path, optional=True)
            else:
                names = _listing(path)
                if str(path) in self.directories and self.directories[str(path)] != names:
                    self.valid = False
                self.directories[str(path)] = names
        except Exception:
            self.valid = False
        finally:
            self.busy = False

    def __exit__(self, *_args):
        self.active = False
        self.sink.__dict__.clear()

    def dependencies(self, restored) -> dict:
        from GUI.services import raw_input_files
        for path in raw_input_files(restored.session.qtegra or self.request.source):
            key = str(Path(path).resolve())
            if key not in self.files:
                self._record_file(path)
        deps = {"files": self.files, "directories": self.directories, "aliases": self.aliases}
        if not self.valid or not _validate(deps):
            raise ValueError("Restore dependencies changed during calculation")
        # Qtegra hashed bytes actually parsed, independently of our open hook.
        for source in restored.session.qtegra.sources:
            if self.files[str(source.path.resolve())]["sha256"] != source.sha256:
                raise ValueError("Raw input changed while reading")
        return deps


def _validate(deps) -> bool:
    # Hashes of resolved files alone would miss a symlink redirected to a new
    # file while the previous target remains unchanged on disk.
    if any(str(Path(path).resolve()) != target for path, target in deps.get("aliases", {}).items()):
        return False
    for path, value in deps["files"].items():
        if value == {"missing": True}:
            try:
                Path(path).stat()
            except FileNotFoundError:
                pass
            else:
                return False
        elif _file(path) != value:
            return False
    return all(_listing(path) == names for path, names in deps["directories"].items())


def discard(request):
    if request is not None:
        for suffix in (".json", ".payload"):
            try:
                (cache_directory() / (request.key + suffix)).unlink(missing_ok=True)
            except Exception:
                pass


def load(request: CacheRequest | None) -> bytes | None:
    """Return validated pickle bytes, or silently discard an invalid entry."""
    if request is None or not enabled():
        return None
    index = None
    try:
        root = cache_directory()
        index_path = root / (request.key + ".json")
        index = json.loads(index_path.read_bytes())
        if index["key"] != request.key or index["engine"] != request.engine or index["format"] != CACHE_FORMAT or not _validate(index["deps"]):
            raise ValueError("Stale cache")
        packed = (root / (request.key + ".payload")).read_bytes()
        if _digest(packed) != index["payload"]:
            raise ValueError("Corrupt cache payload")
        payload = zlib.decompress(packed)
        if len(payload) != index["uncompressed_size"]:
            raise ValueError("Truncated cache payload")
        index["last_used"] = time.time()
        _atomic(index_path, _json(index))  # Last use is metadata, never validity.
        return payload
    except FileNotFoundError:
        # The index commits the entry. A warmer may still be writing a new
        # payload, so never delete it just because its index is not ready yet.
        if index is not None:
            discard(request)
        return None
    except Exception:
        _logger.debug("Results cache miss", exc_info=True)
        discard(request)
        return None


def _digest(payload):
    return {"sha256": hashlib.sha256(payload).hexdigest(), "size": len(payload)}


def _atomic(path, payload):
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(dir=path.parent, prefix=f".results-{os.getpid()}-", delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(payload)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def store(request, payload, deps):
    """Atomically store an entry; all failures leave restoration unaffected."""
    if request is None or not enabled():
        return
    try:
        # Saving the document again while a background restore runs must not
        # attach that result to a different document/key.
        current = prepare(request.project)
        if current is None or current.key != request.key or not _validate(deps):
            return
        root = cache_directory()
        root.mkdir(parents=True, exist_ok=True, mode=0o700)
        packed = zlib.compress(payload, level=1)
        now = time.time()
        index = dict(key=request.key, format=CACHE_FORMAT, engine=request.engine,
                     deps=deps, payload=_digest(packed), uncompressed_size=len(payload),
                     created=now, last_used=now)
        _atomic(root / (request.key + ".payload"), packed)
        _atomic(root / (request.key + ".json"), _json(index))
        evict()
    except Exception:
        _logger.debug("Results cache write skipped", exc_info=True)


def cleanup_process(pid):
    """Remove only abandoned atomic-write files from a child we have reaped."""
    try:
        for path in cache_directory().glob(f".results-{pid}-*"):
            path.unlink(missing_ok=True)
    except Exception:
        _logger.debug("Cache temporary cleanup skipped", exc_info=True)


def evict():
    """Keep payloads and indices under the cap, oldest last use first."""
    root = cache_directory()
    cap = max(0, int(float(os.environ.get("UPBRPY_RESULTS_CACHE_MAX_MB", "2048")) * 1024 * 1024))
    files = [p for p in root.iterdir() if p.suffix in {".json", ".payload"}]
    total = sum(p.stat().st_size for p in files)
    keys = {p.stem for p in files}
    entries = []
    for key in keys:
        paths = [p for p in files if p.stem == key]
        index = root / (key + ".json")
        used = index.stat().st_mtime_ns if index.exists() else 0
        entries.append((used, key, paths))
    for _, _, paths in sorted(entries):
        if total <= cap:
            break
        for path in paths:
            size = path.stat().st_size
            path.unlink(missing_ok=True)
            total -= size


def apply_view(restored, request):
    """Apply current workspace with the same defaults as a fresh restore."""
    from GUI.services import default_visible_channels
    session = restored.session
    workspace = dict(request.document.get("workspace", {}))
    visible = workspace.get("visible_channels")
    channels = [str(c) for c in visible if str(c) in session.channels] if isinstance(visible, list) else []
    session.visible_channels = channels or default_visible_channels(session.channels, session.primary_channel)
    selected = str(workspace.get("selected_spot", "") or "")
    session.selected_spot = selected if selected in session.spot_names else (str(session.experiment["spot_names"].iloc[0]) if not session.experiment.empty else None)
    session.plot_mode = str(workspace.get("plot_mode", "raw"))
    return replace(restored, project_path=request.project, workspace=workspace)
